export function getDayOfYear(year: number, month: number, day: number): number {
  const now = new Date(Date.UTC(year, month - 1, day));
  const start = new Date(Date.UTC(year, 0, 0));
  const diff = now.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  return Math.floor(diff / oneDay);
}

export function quoteForDate(year: number, month: number, day: number): DailyQuote {
  const doy = getDayOfYear(year, month, day);
  const idx = Math.abs(doy - 1) % DAILY_QUOTES_365.length;
  return DAILY_QUOTES_365[idx] ?? DAILY_QUOTES_365[0];
}
